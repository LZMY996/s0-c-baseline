/*
给定一个大小为 n 的数组 nums ，返回其中的多数元素。多数元素是指在数组中出现次数 大于 ⌊ n/2 ⌋ 的元素。

你可以假设数组是非空的，并且给定的数组总是存在多数元素。

 

示例 1：

输入：nums = [3,2,3]
输出：3
示例 2：

输入：nums = [2,2,1,1,1,2,2]
输出：2
*/

/*
 * LeetCode 169. Majority Element
 * 解法：Boyer-Moore投票算法（战场拼杀版）。
 *       将数组视为战场，出现次数超过n/2的多数元素即为"大国"，
 *       不同国家士兵相遇则1换1抵消，相同国家则兵力+1。
 *       因大国人数过半，即便所有小国联合，拼杀后最后站着的必然是大国。
 * 时间复杂度：O(n)，空间复杂度：O(1)
 */
//思路:看到题后找出现次数>n/2的数字，然后想到如果所有不同数字两两拼杀1换1，
//     那小国打小国会互相消耗，大国因为人多，就算被小国消耗一部分，最后也一定有剩余兵力站到最后。就算最坏情况大国人数也仍有一人存活
//     所以遍历整个战场，遇到同国家的就增兵，遇到不同国家就减兵，兵力清零说明当前霸主被全歼，换新的国家当霸主。
//     最后站着的那个国家就是大国。
int majorityElement(int* nums, int numsSize) {
    if (nums == NULL || numsSize <= 0) {    //拿到题先写防御代码
        return 0;
    }
    
    int candidate = nums[0];   //当前战场霸主（候选国家）
    int troops = 1;            //霸主剩余兵力（净票数）
    
    for (int i = 1; i < numsSize; i++) {
        if (nums[i] == candidate) {
            troops++;          //遇到友军，兵力+1
        } else {
            troops--;          //遇到敌军，兵力-1
        }
        
        if (troops == 0) {     //霸主兵力清零，被全歼，换国家
            candidate = nums[i];
            troops = 1;
        }
    }
    
    return candidate;          //最后站着的必然是大国
}